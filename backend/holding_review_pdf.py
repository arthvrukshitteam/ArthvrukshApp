"""PDF exporter for the Portfolio Holding Review Report.

Built on the SAME infrastructure as the proposal PDF (`proposal_pdf`): brand
band + footer (`_decorate`), fonts/colours, card/table helpers, legal name +
ARN constants and the canonical disclaimer wording — so the two documents look
and read as one family and share one source for compliance text.

Layout follows the reference report: title block, client / review dates,
Market / Portfolio Performance, the two-tier FUND-WISE PERFORMANCE REVIEW
table (Proposal data | Current review data), ArthVruksh Observations, and the
disclaimer. The fund table is a flowing, header-repeating table, so any number
of funds (1 … 20+) paginates correctly. A blank previous value is rendered as
"–", never 0.
"""

from __future__ import annotations

from io import BytesIO
from typing import Any, Dict, List

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import CondPageBreak, KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

import bulk_analysis as _ba
import holding_review_engine as hre
import indian_format
import proposal_pdf as pp

REPORT_TITLE = "Portfolio Holding Review Report"
TAGLINE = "Your Goals, Our Guidance"

# Review-specific consent sentence supplied with the reference report. The
# risk wording itself is NOT re-typed here: it is proposal_pdf's canonical text.
REVIEW_CONSENT = (
    "This report is generated by ArthVruksh for review AND any observations if "
    "implemented are with your consent only."
)


def _dash(v: Any) -> str:
    return "–" if v in (None, "") else str(v)


def _fmt_date(iso: Any) -> str:
    from datetime import date
    try:
        return date.fromisoformat(iso).strftime("%d-%b-%y")
    except (TypeError, ValueError):
        return "–"


def _num(v: Any, dp: int = 2) -> str:
    return "–" if v is None else f"{v:,.{dp}f}"


def _pct(v: Any, dp: int = 1) -> str:
    return "–" if v is None else f"{v * 100:.{dp}f}%"


def _signed(v: Any, dp: int = 2, suffix: str = "") -> str:
    return "–" if v is None else f"{v:+,.{dp}f}{suffix}"


def _amount(v: Any) -> str:
    return "–" if v is None else indian_format.indian_group(round(v))


def _fqs_color(fqs: Any):
    """Same thresholds as the Remarks / observation rules (bulk_analysis)."""
    if fqs is None:
        return pp.BRAND
    if fqs < _ba.FQS_BAD_BELOW:
        return pp.ROSE
    if fqs < _ba.FQS_GOOD_FROM:
        return pp.AMBER
    return pp.GREEN


def _fund_table(funds: List[Dict[str, Any]]) -> Table:
    W = pp.CONTENT_WIDTH
    fracs = [0.175, 0.045, 0.072] + [0.0592] * 12
    fracs[-1] += 1.0 - sum(fracs)
    head_a = [pp._cell("Fund Name", True), pp._cell("Rolling<br/>Year", True), pp._cell("Investment", True),
              pp._cell("Proposal Data as per FQS Model", True), "", "", "", "", "",
              pp._cell("Current Review Data as per FQS Model", True), "", "", "", "", ""]
    sub = ["FQS", "WM_P10", "WM_Med", "XIRR<br/>P10", "XIRR<br/>Med", "CV"]
    head_b = ["", "", ""] + [pp._cell(s, True) for s in sub] + [pp._cell(s, True) for s in sub]
    rows: List[List[Any]] = [head_a, head_b]

    fqs_colour_cmds: List[tuple] = []
    for i, f in enumerate(funds):
        prev, cur = f.get("previous") or {}, f.get("current") or {}
        applicable = f.get("investment_type") not in hre.NO_PROPOSAL_DATA
        p = prev if applicable else {}

        def block(m: Dict[str, Any]) -> List[Any]:
            return [
                pp._cell(_num(m.get("fqs"), 1), center=True), pp._cell(_num(m.get("wm_p10")), center=True),
                pp._cell(_num(m.get("wm_med")), center=True), pp._cell(_pct(m.get("irr_p10")), center=True),
                pp._cell(_pct(m.get("irr_med")), center=True), pp._cell(_pct(m.get("cv")), center=True),
            ]

        name = _esc(hre.fund_name(f))
        rows.append([pp._cell(name), pp._cell(_dash(f.get("rolling_year")), center=True),
                     pp._cell(_dash(f.get("investment_type")), center=True)] + block(p) + block(cur))
        r = i + 2
        if cur.get("fqs") is not None:
            fqs_colour_cmds.append(("TEXTCOLOR", (9, r), (9, r), _fqs_color(cur.get("fqs"))))

    t = Table(rows, colWidths=[x * W for x in fracs], repeatRows=2)
    style = pp._grid_style(header_rows=2)
    t.setStyle(style)
    t.setStyle(TableStyle([
        ("SPAN", (3, 0), (8, 0)), ("SPAN", (9, 0), (14, 0)),
        ("SPAN", (0, 0), (0, 1)), ("SPAN", (1, 0), (1, 1)), ("SPAN", (2, 0), (2, 1)),
        ("BACKGROUND", (3, 1), (8, 1), colors.HexColor("#1E3A66")),
        ("BACKGROUND", (9, 1), (14, 1), colors.HexColor("#1D4ED8")),
        ("LINEAFTER", (8, 0), (8, -1), 1.0, pp.BRAND),
        ("LEFTPADDING", (0, 0), (-1, -1), 4), ("RIGHTPADDING", (0, 0), (-1, -1), 4),
    ] + fqs_colour_cmds))
    return t


def _esc(s: str) -> str:
    return str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _summary_block(doc: Dict[str, Any]) -> Table:
    W = pp.CONTENT_WIDTH
    m = hre.summarize_market(doc.get("market") or {})
    plan = doc.get("plan") or {}
    gap = 5 * mm
    lw = W * 0.58
    rw = W - lw - gap

    def row(label: str, pair: Dict[str, Any]) -> List[Any]:
        ch = pair.get("change_pct")
        return [pp._cell(label), pp._cell(_amount(pair.get("previous")), center=True),
                pp._cell(_amount(pair.get("current")), center=True),
                pp._cell("–" if ch is None else f"{ch:+.2f}%", center=True)]

    left = Table(
        [[pp._cell(h, True) for h in ("Market / Portfolio Performance", "Last / Proposal Review", "Current Review", "Change (%)")],
         row("Nifty Index", m["nifty"]), row("Client MF AUM / Invested", m["aum"])],
        colWidths=[lw * 0.37, lw * 0.23, lw * 0.23, lw * 0.17],
    )
    left.setStyle(pp._grid_style())

    goal = plan.get("goal_years")
    right = pp._info_card("Review basis", [
        ("Type of Investment", _dash(hre.investment_type_summary(doc.get("funds") or []))),
        ("Investment Goal Period", f"{goal} Years" if goal else "–"),
        ("Total Quarters Review Completed", _dash(doc.get("quarters_completed"))),
    ], rw)
    out = Table([[left, "", right]], colWidths=[lw, gap, rw])
    out.setStyle(pp._zero_pad())
    return out


def build_report_pdf(doc: Dict[str, Any]) -> bytes:
    client = doc.get("client") or {}
    funds = doc.get("funds") or []
    review_id = doc.get("review_id")
    buf = BytesIO()
    pdf = SimpleDocTemplate(
        buf, pagesize=landscape(A4),
        leftMargin=pp.MARGIN, rightMargin=pp.MARGIN, topMargin=pp.TOP_MARGIN, bottomMargin=pp.BOTTOM_MARGIN,
        title="ArthVruksh Portfolio Holding Review", subject="ArthVruksh Portfolio Holding Review",
        keywords=f"arthvruksh:review:{review_id}:v1" if review_id else "",
    )
    pdf._meta = {
        "client_name": client.get("name") or "—",
        "proposal_date": _fmt_date(doc.get("current_review_date")),
        "doc_label": "Portfolio Holding Review",
    }

    story: List[Any] = []
    title_left = [Paragraph(REPORT_TITLE.upper(), pp.H1),
                  Paragraph(f"{pp.COMPANY_LEGAL_NAME} &nbsp;·&nbsp; {TAGLINE} &nbsp;·&nbsp; ARN # {pp.ARN_NUMBER}", pp.SMALL)]
    story += [Table([[title_left]], colWidths=[pp.CONTENT_WIDTH], style=pp._zero_pad()), Spacer(1, 3 * mm)]

    gap = 5 * mm
    cw = (pp.CONTENT_WIDTH - gap) / 2
    client_card = pp._info_card("Client", [
        ("Client Name", _esc(_dash(client.get("name")))),
        ("PAN Card", _esc(_dash(client.get("pan")))),
    ], cw)
    dates_card = pp._info_card("Review dates", [
        ("Last / Proposal Review", _fmt_date(doc.get("previous_review_date"))),
        ("Current Review", _fmt_date(doc.get("current_review_date"))),
    ], cw)
    story += [pp._card_row([client_card, dates_card], [cw, cw], gap), Spacer(1, 4 * mm)]
    story += [_summary_block(doc), Spacer(1, 4 * mm)]

    story += [CondPageBreak(45 * mm)] + pp._section_title("Fund-wise Performance Review")
    story.append(_fund_table(funds))
    asof = doc.get("data_as_of")
    story.append(Spacer(1, 1.5 * mm))
    story.append(Paragraph(
        "Fund figures are model data (FQS, wealth multiples, rolling-period XIRR and CV) computed by the ArthVruksh FQS "
        "model from fund NAV history" + (f" up to {_fmt_date(asof)}" if asof else "") + "; they are not the client's "
        "actual realised returns. A '–' means the figure is not applicable or not available. Nifty and Client MF AUM / "
        "Invested are as entered by the advisor.", pp.SMALL))
    story.append(Spacer(1, 4 * mm))

    obs = [o for o in (doc.get("observations") or []) if o.get("text") and o.get("included", True)]
    block: List[Any] = pp._section_title("ArthVruksh Observations")
    if obs:
        for i, o in enumerate(obs, 1):
            block.append(Paragraph(f"{i}) {_esc(o['text'])}", pp.CELL))
            block.append(Spacer(1, 1.2 * mm))
    else:
        block.append(Paragraph("No observations recorded.", pp.SMALL))
    story += [KeepTogether(block[:4]), *block[4:], Spacer(1, 4 * mm)]

    # Canonical wording, looked up (not re-typed) from the proposal disclaimer.
    risk = next(t for _, lines in pp.DISCLAIMER_SECTIONS for lbl, t in lines if lbl == "No Guarantees")
    disc = [Paragraph("Standard Disclaimer", pp.H3), Paragraph(pp.DISCLAIMER_INTRO, pp.DISCLAIMER_LABEL),
            Paragraph(risk, pp.DISCLAIMER_SMALL), Paragraph(REVIEW_CONSENT, pp.DISCLAIMER_SMALL)]
    box = Table([[disc]], colWidths=[pp.CONTENT_WIDTH])
    box.setStyle(TableStyle([
        ("BOX", (0, 0), (-1, -1), 0.8, pp.BORDER), ("BACKGROUND", (0, 0), (-1, -1), pp.CARD_BG),
        ("TOPPADDING", (0, 0), (-1, -1), 7), ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
        ("LEFTPADDING", (0, 0), (-1, -1), 11), ("RIGHTPADDING", (0, 0), (-1, -1), 11),
    ]))
    story.append(KeepTogether([box]))

    pdf.build(story, onFirstPage=pp._decorate, onLaterPages=pp._decorate)
    return buf.getvalue()
